#!/usr/bin/env node
// Refresh CSP hashes after inline-script edits; --check validates without writing.
const fs = require('node:fs');
const path = require('node:path');
const { createHash } = require('node:crypto');
const root = path.join(__dirname, '..');
const pages = ['index.html', 'book.html', 'portfolio.html', 'legal.html', 'aftercare.html', 'gift-cards.html'];
const hash = text => `'sha256-${createHash('sha256').update(text).digest('base64')}'`;
const scripts = new Set();
for (const file of pages) {
  const html = fs.readFileSync(path.join(root, file), 'utf8').replace(/\r\n?/g, '\n');
  const re = /<script(?![^>]*\bsrc=)([^>]*)>([\s\S]*?)<\/script>/gi;
  for (const match of html.matchAll(re)) {
    if (!/application\/ld\+json/i.test(match[1])) scripts.add(hash(match[2]));
  }
}
const policy = [
  "default-src 'self'",
  `script-src 'self' https://www.googletagmanager.com ${[...scripts].join(' ')}`,
  `script-src-attr 'unsafe-hashes' ${hash('__libFail()')}`,
  "style-src 'self' 'unsafe-inline'",
  "font-src 'self'",
  "img-src 'self' data: https://*.googleusercontent.com https://www.googletagmanager.com https://*.google-analytics.com",
  "connect-src 'self' https://emmy-reviews.emmalenetattoo.workers.dev https://www.googletagmanager.com https://*.google-analytics.com https://*.google.com",
  'frame-src https://www.google.com https://www.instagram.com https://instagram.com',
  "object-src 'none'",
  "base-uri 'self'",
  "frame-ancestors 'none'",
  "form-action 'self'",
].join('; ');
const headers = '# Generated by node scripts/make-security-headers.js; do not edit hashes by hand.\n'
  + '# CSP is report-only: inspect browser violations before considering enforcement.\n'
  + '# HSTS intentionally excludes includeSubDomains and preload.\n'
  + '/*\n'
  + '  Strict-Transport-Security: max-age=31536000\n'
  + '  X-Content-Type-Options: nosniff\n'
  + '  Referrer-Policy: strict-origin-when-cross-origin\n'
  + '  Content-Security-Policy-Report-Only: ' + policy + '\n';
for (const line of headers.split('\n')) {
  if (line.length > 2000) throw new Error('Cloudflare Pages header-line limit exceeded; split policies by page before publishing.');
}
const target = path.join(root, '_headers');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== headers) {
    console.error('Security headers are stale. Run node scripts/make-security-headers.js and commit _headers.');
    process.exitCode = 1;
  } else console.log('Security headers match all inline scripts.');
} else {
  fs.writeFileSync(target, headers);
  console.log(`Generated report-only CSP for ${pages.length} pages (${scripts.size} distinct inline scripts).`);
}
